class Command(BaseCommand):
    help = "為 TickerMap 的每筆記錄填入 sector 產業標籤"

    def add_arguments(self, parser):
        parser.add_argument("--dry-run", action="store_true", help="只印不寫入")

    def handle(self, *args, **options):
        dry_run = options["dry_run"]

        rows = list(TickerMap.objects.using("summariesdb").all())
        updated = 0
        skipped = 0
        unknown = []

        for row in rows:
            sector = TICKER_SECTOR.get(row.ticker, "")
            if not sector:
                unknown.append(f"  {row.ticker:<15} {row.asset_name}")
                skipped += 1
                continue

            self.stdout.write(
                f"  {row.ticker:<15} {row.asset_name:<15} → {sector}"
            )
            if not dry_run:
                row.sector = sector
                row.save(using="summariesdb", update_fields=["sector"])
            updated += 1

        self.stdout.write("\n" + "=" * 60)
        mode = "[DRY RUN] " if dry_run else ""
        self.stdout.write(f"{mode}完成：{updated} 筆已打標，{skipped} 筆無對應")
        if unknown:
            self.stdout.write("\n未知 ticker（需手動補）：")
            for u in unknown:
                self.stdout.write(u)
